/**
 * Document viewer page — renders markdown content
 */
import { layout, escapeHtml, formatDate, statusBadge } from "./layout";

type User = { email: string; name: string; picture: string };
type Row = Record<string, unknown>;

export function documentPage(user: User, project: Row, doc: Row): string {
  const slug = String(project.slug);
  const content = String(doc.content || "");

  // Simple markdown to HTML (handles headings, lists, code blocks, bold, links, tables)
  const renderedContent = renderMarkdown(content);

  return layout(
    String(doc.title),
    user,
    `<main class="max-w-5xl mx-auto px-4 sm:px-6 lg:px-8 py-8">
      <div class="mb-6">
        <a href="/portal/projects/${escapeHtml(slug)}" class="text-sm text-indigo-600 hover:text-indigo-700 mb-2 inline-block">&larr; ${escapeHtml(String(project.name))}</a>
        <div class="flex items-center gap-3 mb-2">
          <h1 class="text-2xl font-bold text-gray-900">${escapeHtml(String(doc.title))}</h1>
          ${Number(doc.requires_review) ? '<span class="text-xs bg-amber-100 text-amber-700 px-2.5 py-1 rounded-full font-medium">Needs Review</span>' : ""}
        </div>
        <div class="flex items-center gap-3 text-sm text-gray-400">
          ${doc.phase_name ? `<span>${escapeHtml(String(doc.phase_name))}</span><span>&middot;</span>` : ""}
          <span>${escapeHtml(String(doc.category))}</span>
          <span>&middot;</span>
          <span>${formatDate(String(doc.updated_at))}</span>
          ${doc.generated_by ? `<span>&middot;</span><span>Generated by ${escapeHtml(String(doc.generated_by))}</span>` : ""}
          ${doc.confidence != null ? `<span>&middot;</span><span>Confidence: ${Math.round(Number(doc.confidence) * 100)}%</span>` : ""}
        </div>
      </div>

      <div class="bg-white rounded-xl border border-gray-200 p-8">
        ${content
          ? `<div class="markdown-body text-gray-800">${renderedContent}</div>`
          : `<div class="text-center py-16">
              <p class="text-gray-400">Document content not yet synced.</p>
              <p class="text-sm text-gray-300 mt-1">Run a sync from the desktop app to upload content.</p>
            </div>`
        }
      </div>
    </main>
    ${renderedContent.includes('class="mermaid"') ? MERMAID_SCRIPT : ""}`
  );
}

// Loaded only on pages that actually contain a diagram — mermaid is ~2 MB.
const MERMAID_SCRIPT = `<script type="module">
  import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs";
  mermaid.initialize({ startOnLoad: true, securityLevel: "strict" });
</script>`;

function renderMarkdown(md: string): string {
  if (!md) return "";

  let html = escapeHtml(md);

  // Code blocks (``` ... ```) — extracted to placeholders FIRST so the
  // line-oriented transforms below (lists, hr, paragraphs) can't rewrite code
  // or mermaid syntax like `A --> B` / `---`. Reinserted at the end. The
  // placeholder starts with `<x` so the paragraph-wrap regex skips it.
  const blocks: string[] = [];
  html = html.replace(/```(\w*)\n([\s\S]*?)```/g, (_m, lang, code) => {
    // Mermaid fences become diagram elements rendered client-side; the
    // content stays HTML-escaped — mermaid reads textContent, which unescapes.
    const rendered =
      lang === "mermaid"
        ? `<pre class="mermaid">${code.trim()}</pre>`
        : `<pre><code class="language-${lang}">${code.trim()}</code></pre>`;
    blocks.push(rendered);
    return `<x-code-block data-i="${blocks.length - 1}"></x-code-block>`;
  });

  // Inline code
  html = html.replace(/`([^`]+)`/g, "<code>$1</code>");

  // Headings
  html = html.replace(/^######\s+(.+)$/gm, "<h6>$1</h6>");
  html = html.replace(/^#####\s+(.+)$/gm, "<h5>$1</h5>");
  html = html.replace(/^####\s+(.+)$/gm, "<h4>$1</h4>");
  html = html.replace(/^###\s+(.+)$/gm, "<h3>$1</h3>");
  html = html.replace(/^##\s+(.+)$/gm, "<h2>$1</h2>");
  html = html.replace(/^#\s+(.+)$/gm, "<h1>$1</h1>");

  // Bold and italic
  html = html.replace(/\*\*\*(.+?)\*\*\*/g, "<strong><em>$1</em></strong>");
  html = html.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  html = html.replace(/\*(.+?)\*/g, "<em>$1</em>");

  // Blockquotes
  html = html.replace(/^&gt;\s+(.+)$/gm, "<blockquote>$1</blockquote>");

  // Horizontal rules
  html = html.replace(/^---$/gm, "<hr>");

  // Tables
  html = html.replace(
    /^(\|.+\|)\n(\|[-| :]+\|)\n((?:\|.+\|\n?)+)/gm,
    (_m, header: string, _sep, body: string) => {
      const ths = header
        .split("|")
        .filter((c: string) => c.trim())
        .map((c: string) => `<th>${c.trim()}</th>`)
        .join("");
      const rows = body
        .trim()
        .split("\n")
        .map((row: string) => {
          const tds = row
            .split("|")
            .filter((c: string) => c.trim())
            .map((c: string) => `<td>${c.trim()}</td>`)
            .join("");
          return `<tr>${tds}</tr>`;
        })
        .join("");
      return `<table><thead><tr>${ths}</tr></thead><tbody>${rows}</tbody></table>`;
    }
  );

  // Unordered lists
  html = html.replace(/^(\s*)-\s+(.+)$/gm, "<li>$2</li>");
  html = html.replace(/((?:<li>.*<\/li>\n?)+)/g, "<ul>$1</ul>");

  // Links
  html = html.replace(
    /\[([^\]]+)\]\(([^)]+)\)/g,
    '<a href="$2" target="_blank" class="text-indigo-600 hover:underline">$1</a>'
  );

  // Paragraphs — wrap remaining lines
  html = html.replace(/^(?!<[a-z])((?!<\/)[^\n]+)$/gm, "<p>$1</p>");

  // Clean up empty paragraphs
  html = html.replace(/<p>\s*<\/p>/g, "");

  // Reinsert extracted code blocks
  html = html.replace(/<x-code-block data-i="(\d+)"><\/x-code-block>/g, (_m, i) => blocks[Number(i)]);

  return html;
}
