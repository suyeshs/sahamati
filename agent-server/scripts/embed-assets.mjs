#!/usr/bin/env node
// Codegen: inline the CLI templates/scaffold files AND the agent prompts into
// plain-TS modules so they are available at runtime in BOTH the Node/tsc-built
// server and Bun-compiled binaries — without runtime filesystem reads or
// Bun-only text import attributes. Installed desktop bundles have no source
// tree next to the sidecar, so the compiled binary can only see what is
// embedded here.
//
// Run via `npm run embed` (also runs automatically before build:cli / build).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cliDir = join(here, "..", "src", "cli");
const templatesDir = join(cliDir, "templates");
const scaffoldDir = join(cliDir, "scaffold");
const outFile = join(cliDir, "lib", "embedded.ts");
const promptsDir = join(here, "..", "src", "prompts");
const promptsOutFile = join(here, "..", "src", "agents", "embedded-prompts.ts");
const migrationsDir = join(here, "..", "src", "db", "migrations");
const migrationsOutFile = join(here, "..", "src", "db", "embedded-migrations.ts");

function lit(s) {
  // Encode as a JSON string literal — safe for any content (backticks,
  // backslashes, template-literal sequences, etc.).
  return JSON.stringify(s);
}

const templates = {};
for (const f of readdirSync(templatesDir).filter((f) => f.endsWith(".md"))) {
  const key = f.replace(/\.md$/, "");
  templates[key] = readFileSync(join(templatesDir, f), "utf-8");
}

const scaffold = {};
for (const f of readdirSync(scaffoldDir)) {
  scaffold[f] = readFileSync(join(scaffoldDir, f), "utf-8");
}

const banner = `// AUTO-GENERATED by scripts/embed-assets.mjs — do not edit by hand.
// Edit the source files under src/cli/templates/ and src/cli/scaffold/,
// then run \`npm run embed\` (build scripts do this automatically).
`;

const body =
  banner +
  `\nexport const TEMPLATES: Record<string, string> = {\n` +
  Object.entries(templates)
    .map(([k, v]) => `  ${lit(k)}: ${lit(v)},`)
    .join("\n") +
  `\n};\n\nexport const SCAFFOLD: Record<string, string> = {\n` +
  Object.entries(scaffold)
    .map(([k, v]) => `  ${lit(k)}: ${lit(v)},`)
    .join("\n") +
  `\n};\n`;

writeFileSync(outFile, body, "utf-8");
process.stdout.write(
  `Embedded ${Object.keys(templates).length} templates, ${Object.keys(scaffold).length} scaffold files → ${outFile}\n`
);

const prompts = {};
for (const f of readdirSync(promptsDir).filter((f) => f.endsWith(".md")).sort()) {
  prompts[f] = readFileSync(join(promptsDir, f), "utf-8");
}

const promptsBody =
  `// AUTO-GENERATED by scripts/embed-assets.mjs — do not edit by hand.
// Edit the source files under src/prompts/, then run \`npm run embed\`
// (build scripts do this automatically).
` +
  `\nexport const EMBEDDED_PROMPTS: Record<string, string> = {\n` +
  Object.entries(prompts)
    .map(([k, v]) => `  ${lit(k)}: ${lit(v)},`)
    .join("\n") +
  `\n};\n`;

writeFileSync(promptsOutFile, promptsBody, "utf-8");
process.stdout.write(
  `Embedded ${Object.keys(prompts).length} prompts → ${promptsOutFile}\n`
);

const migrations = {};
for (const f of readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort()) {
  migrations[f] = readFileSync(join(migrationsDir, f), "utf-8");
}

const migrationsBody =
  `// AUTO-GENERATED by scripts/embed-assets.mjs — do not edit by hand.
// Edit the .sql files under src/db/migrations/, then run \`npm run embed\`
// (build scripts do this automatically).
` +
  `\nexport const EMBEDDED_MIGRATIONS: Record<string, string> = {\n` +
  Object.entries(migrations)
    .map(([k, v]) => `  ${lit(k)}: ${lit(v)},`)
    .join("\n") +
  `\n};\n`;

writeFileSync(migrationsOutFile, migrationsBody, "utf-8");
process.stdout.write(
  `Embedded ${Object.keys(migrations).length} migrations → ${migrationsOutFile}\n`
);
